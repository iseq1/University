class DataGenerator:
    """Класс, описывающий логику генерации синтетических данных"""


    def __init__(self):
        self.parser = ArgumentParser(description=__doc__)


    @staticmethod
    def _write_json(path: Path, rows: list[dict[str, Any]]) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")


    @staticmethod
    def _write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        if not rows:
            return
        with path.open("w", newline="", encoding="utf-8-sig") as file:
            writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
            writer.writeheader()
            writer.writerows(rows)


    @staticmethod
    def build_glossary() -> list[dict[str, str]]:
        """Подготавливает для каждого из отобранных общих игровых терминов по пять контекстных словарных статей"""

        rows = []
        for term, definition in GLOSSARY_TERMS:
            for context in CONTEXTS:
                rows.append({
                    "term": f"{term} ({context})",
                    "definition": f"{definition} Контекст применения: {context}; значение зависит от конкретной игры.",
                    "category": context.removeprefix("в "),
                })

        return rows


    @staticmethod
    def build_knowledge_examples(count: int, split: str) -> list[dict[str, str]]:
        """Создание отдельных примеров синтетических профилей и их кратких сводок"""
        rows = []

        for index in range(count):
            game = GAMES[(index + (17 if split == "test" else 0)) % len(GAMES)]
            style = STYLES[(index // len(GAMES) + (2 if split == "test" else 0)) % len(STYLES)]
            genre = GENRES[(index // (len(GAMES) * len(STYLES))) % len(GENRES)]

            hours = 50 + ((index * 137 + (9000 if split == "test" else 0)) % 4950)
            games_count = 4 + (index * 7) % 86
            achievement_rate = 10 + (index * 13) % 91

            source = (
                f"Synthetic {split} profile {index + 1:04d}; favorite_game={game}; "
                f"preferred_style={style}; favorite_genre={genre}; total_playtime_hours={hours}; "
                f"games_owned={games_count}; achievement_completion_percent={achievement_rate}."
            )

            target = (
                f"Игрок предпочитает {style} стиль и чаще выбирает жанр «{genre}». "
                f"В библиотеке выделяется {game}; суммарное время в играх — около {hours} часов. "
                f"В профиле {games_count} игр, доля выполненных достижений в условном наборе — {achievement_rate}%."
            )

            rows.append({
                "source_text": source,
                "target_text": target,
                "category": genre
            })

        return rows


    def generate_datasets(self, output_dir: Path = OUTPUT_DIR, train_count: int = 1000, test_count: int = 200) -> dict[str, int]:
        """Создание обучающих данных, глоссария и отдельной выборки для оценки"""

        if train_count < 1 or test_count < 1:
            raise ValueError(
                "Число обучающих и тестовых примеров должно быть положительным"
            )

        if len(GLOSSARY_TERMS) * len(CONTEXTS) < 500:
            raise ValueError(
                "Словарь исходных терминов должен обеспечивать не менее 500 записей"
            )

        train = self.build_knowledge_examples(count=train_count, split="train")
        test = self.build_knowledge_examples(count=test_count, split="test")
        glossary = self.build_glossary()

        train_sources = {
            row["source_text"] for row in train
        }

        test_sources = {
            row["source_text"] for row in test
        }

        if len(train_sources) != len(train) or len(test_sources) != len(test):
            raise ValueError(
                "Обнаружены дубликаты в примерах"
            )

        if train_sources & test_sources:
            raise ValueError(
                "Обучающая и тестовая выборки пересекаются"
            )

        if len({row["term"].casefold() for row in glossary}) != len(glossary):
            raise ValueError(
                "Обнаружены повторяющиеся термины глоссария"
            )

        datasets = {
            "knowledge_base_train": train,
            "knowledge_base_test": test,
            "glossary": glossary,
        }

        for name, rows in datasets.items():
            self._write_json(path=output_dir / f"{name}.json", rows=rows)
            self._write_csv(path=output_dir / f"{name}.csv", rows=rows)

        self._write_json(
            path=output_dir / "dataset_metadata.json",
            rows=[
                {
                    "name": "knowledge_base_train",
                    "records": len(train),
                    "origin": "synthetic"
                },
                {
                    "name": "knowledge_base_test",
                    "records": len(test),
                    "origin": "synthetic",
                    "overlap_with_train": 0
                },
                {
                    "name": "glossary",
                    "records": len(glossary),
                    "unique_terms": len({row['term'].casefold() for row in glossary}),
                    "origin": "curated general gaming definitions expanded by context"
                },
            ]
        )

        return {
            "knowledge_base_train": len(train),
            "knowledge_base_test": len(test),
            "glossary": len(glossary)
        }


    def main(self) -> None:
        """Основной метод обработчика"""
        self.parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIR)
        self.parser.add_argument("--train-count", type=int, default=1000)
        self.parser.add_argument("--test-count", type=int, default=200)

        args = self.parser.parse_args()
        counts = self.generate_datasets(
            output_dir=args.output_dir,
            train_count=args.train_count,
            test_count=args.test_count
        )

        for name, count in counts.items():
            print(f"{name}: {count}")

        print(f"Файлы сохранены в: {args.output_dir}")


if __name__ == "__main__":
    DataGenerator().main()
